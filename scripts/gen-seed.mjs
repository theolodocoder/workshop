// Writes supabase/{before,rescue}/supabase/seed.sql from the Northfold catalog.
// Both stacks get the same products, the two fake shoppers (Ada and Ben) and their orders.
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const { products, SHOPPERS, BEN_TARGET_ORDER_ID } = await import(root + "packages/catalog/src/index.ts");

const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const price = (slug) => products.find((p) => p.slug === slug).priceCents;
const pid = (slug) => products.find((p) => p.slug === slug).id;

const orders = [
  { id: "00000000-0000-4000-b000-0000000000a1", user: SHOPPERS.ada.id, items: [["granite-45-pack", 1], ["enamel-camp-mug", 2]] },
  { id: "00000000-0000-4000-b000-0000000000a2", user: SHOPPERS.ada.id, items: [["crag-leather-boot", 1]] },
  { id: BEN_TARGET_ORDER_ID, user: SHOPPERS.ben.id, items: [["summit-light-tent", 1], ["skyward-down-bag", 1], ["flameline-stove", 1]] },
  { id: "00000000-0000-4000-b000-0000000000b2", user: SHOPPERS.ben.id, items: [["basecamp-knit-cap", 2]] },
];

const lines = [
  "-- Generated by scripts/gen-seed.mjs. Do not edit by hand.",
  "",
  "-- Remove anonymous demo visitors from earlier runs (resets keep the two seeded shoppers).",
  "delete from auth.users where is_anonymous;",
  "",
  "insert into public.products (id, slug, name, category, price_cents, description, image_file) values",
  products
    .map((p) => `  (${q(p.id)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.category)}, ${p.priceCents}, ${q(p.description)}, ${q(p.image.file)})`)
    .join(",\n") + ";",
  "",
  "-- Two fake shoppers. They never sign in; they only own the demo orders.",
  "insert into auth.users (id, instance_id, aud, role, email, created_at, updated_at, is_anonymous) values",
  Object.values(SHOPPERS)
    .map((s) => `  (${q(s.id)}, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', ${q(s.name.toLowerCase() + "@demo.northfold.test")}, now(), now(), false)`)
    .join(",\n") + "\non conflict (id) do nothing;",
  "",
  "insert into public.profiles (id, display_name) values",
  Object.values(SHOPPERS).map((s) => `  (${q(s.id)}, ${q(s.name)})`).join(",\n") + "\non conflict (id) do nothing;",
  "",
];

for (const o of orders) {
  const total = o.items.reduce((sum, [slug, qty]) => sum + price(slug) * qty, 0);
  lines.push(`insert into public.orders (id, user_id, total_cents) values (${q(o.id)}, ${q(o.user)}, ${total});`);
  lines.push(
    "insert into public.order_items (order_id, product_id, qty, unit_price_cents) values " +
      o.items.map(([slug, qty]) => `(${q(o.id)}, ${q(pid(slug))}, ${qty}, ${price(slug)})`).join(", ") + ";",
  );
}

const sql = lines.join("\n") + "\n";
for (const stack of ["before", "rescue"]) {
  await writeFile(`${root}supabase/${stack}/supabase/seed.sql`, sql);
}
console.log(`seed.sql written for before and rescue (${products.length} products, ${orders.length} orders)`);
